"""Build a self-contained Earth Engine demo from audited repository outputs."""
from pathlib import Path
import json
import geopandas as gpd
import pandas as pd
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'earth_engine'
g = gpd.read_file(ROOT / 'output/equity/lor_watering_equity_2020_2025.gpkg')
p = pd.read_csv(ROOT / 'data/processed/foundation/lor_month_recorded_watering_2020_2025.csv', dtype={'plr_id': str})
assert not p.duplicated(['plr_id', 'month']).any()
assert len(g) == 542 and len(p) == 542 * 68
assert int(p.recorded_watering_events.sum()) == 57786
assert abs(p.recorded_litres.sum() - 2249502) < .01
months = sorted(p.month.unique())
cols = ['plr_id','plr_name','District','inventory_trees','watering_reach_pct','social_status_score','thermal_burden','green_provision']
g = g[cols + ['geometry']].copy()
# Display only: analytical boundaries and numbers remain unchanged upstream.
g.geometry = g.geometry.simplify(20, preserve_topology=True)
g = g.to_crs(4326)
features = json.loads(g.to_json(drop_id=True))['features']
series = {}
for key, group in p.groupby('plr_id'):
    group = group.set_index('month').reindex(months)
    assert group.recorded_watering_events.notna().all()
    series[key] = [[int(r.recorded_watering_events), round(r.recorded_litres, 3)] for r in group.itertuples()]
assert set(series) == set(g.plr_id)
daily = pd.read_csv(ROOT / 'output/rq1_daily/tables/city_day_linked_baseline.csv')
daily = json.loads(daily[['date','events','air_temperature_max_c','rainfall_mm']].to_json(orient='records'))
payload = {'features': features, 'months': [m[:7] for m in months], 'series': series, 'daily': daily}
text = '// GENERATED by build_demo.py. Paste this entire file into the Earth Engine Code Editor.\nvar DATA = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':'), allow_nan=False) + ';\n'
text += (OUT / 'atlas_ui.js').read_text()
(OUT / 'berlin_atlas_demo.js').write_text(text)
print(f'Validated 542 areas, 68 months, 57,786 events, 2,249,502 litres. Script: {len(text.encode()):,} bytes')
